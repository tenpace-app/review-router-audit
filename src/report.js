const valueOrNA = (value, suffix = "") => (value === null ? "n/a" : `${value}${suffix}`);

function listPullRequests(numbers) {
  return numbers.length === 0 ? "None" : numbers.slice(0, 12).map((number) => `#${number}`).join(", ");
}

export function summaryMarkdown(report, setup = null) {
  const lines = [
    "# Review Router audit",
    "",
    `**${report.repository} · ${valueOrNA(report.score, "/100")}**`,
    "",
    "| Signal | Result |",
    "| --- | ---: |",
    `| Open PRs | ${report.openPullRequests.count}${report.openPullRequests.truncated ? "+" : ""} |`,
    `| Stale PRs | ${report.stalePullRequests.count} |`,
    `| Unowned PRs | ${report.unownedPullRequests.count} |`,
    `| Median first review | ${valueOrNA(report.medianFirstReviewHours.value, " hours")} |`,
    `| Busiest reviewer share | ${valueOrNA(report.reviewerConcentration.value, "%")} |`,
    `| CODEOWNERS gaps | ${report.codeowners.gapCount} |`,
    `| Overloaded reviewers | ${report.overloadedReviewers.count} |`,
    "",
    `Stale: ${listPullRequests(report.stalePullRequests.numbers)}`,
    "",
    `Unowned: ${listPullRequests(report.unownedPullRequests.numbers)}`,
  ];

  if (!report.codeowners.present) {
    lines.push("", "⚠️ No CODEOWNERS file was found in a supported location.");
  } else if (report.codeowners.gaps.length > 0) {
    lines.push("", "## CODEOWNERS gaps");
    for (const gap of report.codeowners.gaps.slice(0, 10)) {
      lines.push(
        `- PR #${gap.number}: ${gap.uncoveredFileCount} uncovered file${gap.uncoveredFileCount === 1 ? "" : "s"}`
      );
    }
  }

  if (report.overloadedReviewers.reviewers.length > 0) {
    lines.push("", "## Open review load");
    for (const reviewer of report.overloadedReviewers.reviewers) {
      lines.push(`- @${reviewer.login}: ${reviewer.openRequests} open requests`);
    }
  }

  if (report.healthUrl && report.badgeUrl) {
    lines.push(
      "",
      `[Open the shareable health report](${report.healthUrl})`,
      "",
      `<a href="${report.healthUrl}"><img alt="PR review health" src="${report.badgeUrl}"></a>`
    );
  } else {
    lines.push("", "The public report and live badge are available for public repositories.");
  }
  lines.push("", "## Route these reviews to Slack");
  if (setup?.url) {
    lines.push(
      "",
      `[Continue this repository's Review Router setup](${setup.url})`,
      "",
      "Sign in to Tenpace to lock the exact destination, then complete GitHub and Slack authorization."
    );
  } else {
    lines.push(
      "",
      "[Create a human-authenticated setup link with the Review Router Setup Action](https://github.com/tenpace-app/review-router-setup)"
    );
  }
  lines.push(
    "",
    "<sub>Generated by Review Router Audit. The Action reports repository data and does not rank individual developers.</sub>"
  );
  return lines.join("\n");
}

export function commentMarkdown(report) {
  return [
    "<!-- review-router-audit -->",
    "## Review Router audit",
    "",
    `Repository score: **${valueOrNA(report.score, "/100")}**`,
    "",
    `- Stale open PRs: ${report.stalePullRequests.count}`,
    `- Unowned open PRs: ${report.unownedPullRequests.count}`,
    `- Median first review: ${valueOrNA(report.medianFirstReviewHours.value, " hours")}`,
    `- CODEOWNERS gaps: ${report.codeowners.gapCount}`,
    "",
    report.healthUrl
      ? `[View the full public report](${report.healthUrl})`
      : "The public report is available for public repositories.",
  ].join("\n");
}
